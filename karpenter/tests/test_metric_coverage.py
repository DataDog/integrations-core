"""Check that every metric of the supported Karpenter release is collected and described.

The check only submits the metrics listed in `METRIC_MAP` and drops the rest without an error.
A metric that Karpenter adds therefore goes unnoticed.
These tests run the check on an exposition of the metrics that the supported release registers.
The fixture is generated by `scripts/karpenter_metrics_v1`.
To support a newer release, bump Karpenter in that tool and regenerate the fixture.
A second exposition, written by hand, covers metrics that older v1 releases name differently.
"""

import pytest

from datadog_checks.dev.utils import get_metadata_metrics
from datadog_checks.karpenter import KarpenterCheck
from datadog_checks.karpenter.metrics import METRIC_MAP

from .common import get_fixture_path

KARPENTER_METRICS_V1_FILE = 'karpenter_metrics_v1.txt'
KARPENTER_METRICS_V1_RENAMED_FILE = 'karpenter_metrics_v1_renamed.txt'
METRICS_FILES = [KARPENTER_METRICS_V1_FILE, KARPENTER_METRICS_V1_RENAMED_FILE]

# OpenMetrics V2 submits a counter as `.count`, and a histogram or a summary as several metrics with these suffixes.
TYPE_SUFFIXES = ('.count', '.sum', '.bucket', '.quantile')


def read_metrics(metrics_file: str) -> dict[str, str]:
    """Return the type of each metric that an exposition lists, by name."""
    with open(get_fixture_path(metrics_file)) as f:
        return dict(line.split()[2:4] for line in f if line.startswith('# TYPE '))


def map_key(name: str, metric_type: str) -> str | None:
    """Return the key of `METRIC_MAP` that collects the metric Karpenter registers as `name`, if there is one.

    OpenMetrics V2 reports a counter without its `_total` suffix, so `METRIC_MAP` is keyed by the bare name.
    """
    key = name.removesuffix('_total') if metric_type == 'counter' else name
    return key if key in METRIC_MAP else None


def datadog_name(key: str) -> str:
    """Return the name the check submits for a `METRIC_MAP` key, before any type suffix."""
    value = METRIC_MAP[key]
    return f'karpenter.{value["name"] if isinstance(value, dict) else value}'


def run_check(metrics_file, dd_run_check, instance, mock_http_response):
    mock_http_response(file_path=get_fixture_path(metrics_file))
    dd_run_check(KarpenterCheck('karpenter', {}, [instance]))


@pytest.mark.parametrize('metrics_file', METRICS_FILES)
def test_every_karpenter_metric_is_submitted(
    metrics_file, allow_service_tag, dd_run_check, instance, aggregator, mock_http_response
):
    run_check(metrics_file, dd_run_check, instance, mock_http_response)
    submitted = set(aggregator.metric_names)

    dropped = []
    for name, metric_type in read_metrics(metrics_file).items():
        key = map_key(name, metric_type)
        if key is None:
            dropped.append(f'{name}: not in METRIC_MAP')
            continue
        base = datadog_name(key)
        if not {base, *(f'{base}{suffix}' for suffix in TYPE_SUFFIXES)} & submitted:
            dropped.append(f'{name}: the check does not submit {base}')

    names = '\n  '.join(dropped)
    assert not dropped, f'{len(dropped)} Karpenter metrics are dropped by the check:\n  {names}'


@pytest.mark.parametrize('metrics_file', METRICS_FILES)
def test_submitted_karpenter_metrics_are_in_metadata(
    metrics_file, allow_service_tag, dd_run_check, instance, aggregator, mock_http_response
):
    run_check(metrics_file, dd_run_check, instance, mock_http_response)

    aggregator.assert_metrics_using_metadata(get_metadata_metrics())
